#!/bin/bash
# PreToolUse guard (Edit/Write): the Xcode project and the Info.plists listed in project.yml are
# written by xcodegen, so an edit there is lost on the next generate. Exit 2 blocks the edit and
# shows Claude the message.
input=$(cat)
path=$(printf '%s' "$input" | grep -oE '"file_path" *: *"[^"]*"' | head -1 | sed -E 's/.*: *"(.*)"/\1/')
[ -n "$path" ] || exit 0
case "$path" in
  *.xcodeproj/*|*.pbxproj|*.xcworkspace/*)
    echo "Blocked: $path is generated by xcodegen and not committed. Change project.yml instead (new source files are picked up from the target's folder automatically)." >&2
    exit 2 ;;
  */Info.plist)
    root="${CLAUDE_PROJECT_DIR:-.}"
    rel="${path#"$root"/}"
    if [ -f "$root/project.yml" ] && grep -qE "^ *path: *$rel *$" "$root/project.yml"; then
      echo "Blocked: $rel is written by xcodegen from the info: properties in project.yml. Add the key there instead." >&2
      exit 2
    fi ;;
esac
exit 0
